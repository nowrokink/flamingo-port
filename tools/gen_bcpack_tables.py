"""Generate runtime/shims/bcpack_tables.h from a BCPack table file (77,982 bytes).

The table file holds BCPack's constant tables, little-endian, no padding:
  128 models x 9 u16      rANS band frequencies; model 16 g + q has g + 2 bands, band b > 0 holding 2^(b-1)
                          symbols of that frequency, and they tile 65536
  rank tables             BC1 256 B, BC3 alpha 64 B and colour 256 B, BC4 64 B, BC5 64 B
  512 u16                 BC7 control words (mode, rotation, index selection, subsets, partition)
  255 dictionary entries per format, standing in for the blocks before the first:
    BC1 6 + 16 B, BC3 8 + 32 B, BC4 2 + 16 B, BC5 4 + 32 B (endpoints, then indices)
    BC6H  u8 (unused), 12 u16 endpoints, u8 mode, 16 i16 indices
    BC7   u16 control, 24 u16 endpoint rows, 2 u8 index widths, 2 B (unused), 16 + 15 i16 indices

    python -I tools/gen_bcpack_tables.py <table file>            # rewrites runtime/shims/bcpack_tables.h
    python -I tools/gen_bcpack_tables.py <table file> --check    # exit 1 if the header is out of date
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, "runtime", "shims", "bcpack_tables.h")
SIZE = 128 * 9 * 2 + 256 + 64 + 256 + 64 + 64 + 512 * 2 + 255 * (6 + 16 + 8 + 32 + 2 + 16 + 4 + 32 + 25 + 33 + 50 + 66)


class Reader:
    def __init__(self, data):
        self.data, self.at = data, 0

    def take(self, fmt):
        v = struct.unpack_from("<" + fmt, self.data, self.at)
        self.at += struct.calcsize("<" + fmt)
        return list(v)


def join(values):
    return ", ".join(str(v) for v in values)


def render(data):
    if len(data) != SIZE:
        raise ValueError("a BCPack table file is %d bytes, this one %d" % (SIZE, len(data)))
    r = Reader(data)
    models = [r.take("9H") for _ in range(128)]
    for m, f in enumerate(models):
        bands = m // 16 + 2
        if any(v == 0 for v in f[:bands]) or sum(v << max(0, b - 1) for b, v in enumerate(f[:bands])) != 65536:
            raise ValueError("model %d does not tile 65536" % m)
    ranks = [("kRank1", r.take("256B")), ("kRank3Alpha", r.take("64B")), ("kRank3Colour", r.take("256B")),
             ("kRank4", r.take("64B")), ("kRank5", r.take("64B"))]
    ctrl7 = r.take("512H")
    plain = []
    for name, ep, ix in (("kDictBc1", 6, 16), ("kDictBc3", 8, 32), ("kDictBc4", 2, 16), ("kDictBc5", 4, 32)):
        rows = []
        for _ in range(255):
            e, i = r.take("%dB" % ep), r.take("%dB" % ix)
            rows.append((e + [0] * (8 - ep), i + [0] * (32 - ix)))
        plain.append((name, rows))
    bc6 = []
    for _ in range(255):
        r.take("B")
        e = r.take("12H")
        mode = r.take("B")[0]
        ix = [v & 0xFFFF for v in r.take("16h")]
        bc6.append((e, mode, ix))
    bc7 = []
    for _ in range(255):
        ctrl = r.take("H")[0]
        rows = r.take("24H")
        bits = r.take("2B")
        r.take("2B")
        ix = [v & 0xFFFF for v in r.take("31h")] + [0]
        bc7.append((ctrl, rows, bits, ix))
    assert r.at == SIZE

    out = [
        "// Generated by tools/gen_bcpack_tables.py; do not edit. BCPack's constant tables (see bcpack.cpp).",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace rt::bcpack::tables {",
        "",
        "// rANS band frequencies: model 16 g + q (g = symbol bits - 1) has g + 2 bands; band b > 0 holds 2^(b-1)",
        "// symbols, each of that frequency.",
        "inline constexpr uint16_t kModels[128][9] = {",
    ]
    out += ["    {%s}," % join(f) for f in models]
    out.append("};")
    out.append("")
    out.append("// Index ranks: a symbol's index residuals, 2-bit quads (BC1, BC3 colour) or 3-bit pairs (BC3 alpha, BC4, BC5).")
    for name, vals in ranks:
        out.append("inline constexpr uint8_t %s[%d] = {" % (name, len(vals)))
        for i in range(0, len(vals), 16):
            out.append("    %s," % join(vals[i:i + 16]))
        out.append("};")
    out.append("")
    out.append("// BC7 control words: bits 0-2 mode, 3-4 rotation, 5 index selection, 6-7 subsets, 8-13 partition.")
    out.append("inline constexpr uint16_t kControl7[512] = {")
    for i in range(0, 512, 16):
        out.append("    %s," % join(ctrl7[i:i + 16]))
    out.append("};")
    out += [
        "",
        "// Dictionaries: entry k stands in for the block k + 1 places before the first.",
        "struct Plain {",
        "    uint8_t ep[8];   // BC1 R0 G0 B0 R1 G1 B1; BC3 those then A0 A1; BC4 A0 A1; BC5 R0 R1 G0 G1",
        "    uint8_t ix[32];  // index residual bases, pixel order (BC3: alpha then colour; BC5: red then green)",
        "};",
        "struct Bc6 {",
        "    uint16_t e[4][3];  // endpoints R G B, left-aligned, top bit flipped",
        "    uint8_t mode;",
        "    uint16_t ix[16];",
        "};",
        "struct Bc7 {",
        "    uint16_t control;",
        "    uint16_t rows[3][8];  // per subset R0 R1 G0 G1 B0 B1 A0 A1, left-aligned",
        "    uint8_t bits[2];      // index widths of the two index sets",
        "    uint16_t ix[2][16];",
        "};",
    ]
    for name, rows in plain:
        out.append("inline constexpr Plain %s[255] = {" % name)
        out += ["    {{%s}, {%s}}," % (join(e), join(i)) for e, i in rows]
        out.append("};")
    out.append("inline constexpr Bc6 kDictBc6[255] = {")
    for e, mode, ix in bc6:
        out.append("    {{{%s}, {%s}, {%s}, {%s}}, %d, {%s}}," % (join(e[0:3]), join(e[3:6]), join(e[6:9]), join(e[9:12]),
                                                             mode, join(ix)))
    out.append("};")
    out.append("inline constexpr Bc7 kDictBc7[255] = {")
    for ctrl, rows, bits, ix in bc7:
        out.append("    {%d, {{%s}, {%s}, {%s}}, {%s}, {{%s}, {%s}}}," % (ctrl, join(rows[0:8]), join(rows[8:16]),
                                                                    join(rows[16:24]), join(bits), join(ix[:16]),
                                                                    join(ix[16:])))
    out.append("};")
    out.append("")
    out.append("}  // namespace rt::bcpack::tables")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    with open(sys.argv[1], "rb") as f:
        rendered = render(f.read())
    if "--check" in sys.argv:
        with open(TARGET, encoding="utf-8") as f:
            ok = f.read() == rendered
        print("bcpack_tables.h is %s" % ("up to date" if ok else "OUT OF DATE"))
        return 0 if ok else 1
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write(rendered)
    print("wrote", TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main())
