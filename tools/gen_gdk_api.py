"""Writes runtime/shims/gdk_api.inc: the GDK runtime's functions as (name, class id, interface id, slot), the way the
public PC GDK's xgameruntime.lib reaches them through QueryApiImpl. Facts only (names, GUIDs, slot numbers); the list
is read from a table of them, such as the one the xcl project generates from that library.

Usage: python -I tools/gen_gdk_api.py <gdk_table.rs> [out]
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
out = sys.argv[2] if len(sys.argv) > 2 else "runtime/shims/gdk_api.inc"
rows = re.findall(r'\("(\w+)", 0x([0-9a-f]{32}), 0x([0-9a-f]{32}), (\d+)\)', src)


def guid(h):
    return (f"{{0x{h[0:8]}, 0x{h[8:12]}, 0x{h[12:16]}, "
            f"{{0x{h[16:18]}, 0x{h[18:20]}, 0x{h[20:22]}, 0x{h[22:24]}, 0x{h[24:26]}, 0x{h[26:28]}, 0x{h[28:30]}, 0x{h[30:32]}}}}}")


with open(out, "w", newline="\n") as f:
    f.write("// Generated by tools/gen_gdk_api.py: {name, class id, interface id, slot} of every GDK runtime function.\n")
    for name, cls, iid, slot in rows:
        f.write(f'{{"{name}", {guid(cls)}, {guid(iid)}, {slot}}},\n')
print(f"{len(rows)} functions -> {out}")
