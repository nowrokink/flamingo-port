"""Writes runtime/gpu/gfx10_swizzle.inc: the address equations of the GFX10 swizzle modes the console uses, for its
pipe / packer configuration (Series X: 32 pipes, 8 packers; only the XOR modes depend on it).

Each equation gives, per address bit inside a block, the x, y and z coordinate bits XORed into it (16-bit masks of
element coordinates). It is read from AMD's addrlib swizzle tables (Mesa's gfx10SwizzlePattern.h, MIT licence), the
RbPlus ones (RDNA2), choosing the entry whose comment names the configuration and element size.

Usage: python -I tools/gen_swizzle.py <gfx10SwizzlePattern.h> [out] [--pipes "32 pipes (8 PKRs)"]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from amd_swizzle import load  # noqa: E402

# (swizzle mode, thick 3D) -> table; block size log2
MODES = {
    (1, False): ("GFX10_SW_256_S_RBPLUS_PATINFO", 8),
    (2, False): ("GFX10_SW_256_D_RBPLUS_PATINFO", 8),
    (5, False): ("GFX10_SW_4K_S_RBPLUS_PATINFO", 12),
    (6, False): ("GFX10_SW_4K_D_RBPLUS_PATINFO", 12),
    (9, False): ("GFX10_SW_64K_S_RBPLUS_PATINFO", 16),
    (10, False): ("GFX10_SW_64K_D_RBPLUS_PATINFO", 16),
    (17, False): ("GFX10_SW_64K_S_T_RBPLUS_PATINFO", 16),
    (18, False): ("GFX10_SW_64K_D_T_RBPLUS_PATINFO", 16),
    (21, False): ("GFX10_SW_4K_S_X_RBPLUS_PATINFO", 12),
    (22, False): ("GFX10_SW_4K_D_X_RBPLUS_PATINFO", 12),
    (24, False): ("GFX10_SW_64K_Z_X_1xaa_RBPLUS_PATINFO", 16),
    (25, False): ("GFX10_SW_64K_S_X_RBPLUS_PATINFO", 16),
    (26, False): ("GFX10_SW_64K_D_X_RBPLUS_PATINFO", 16),
    (27, False): ("GFX10_SW_64K_R_X_1xaa_RBPLUS_PATINFO", 16),
    (5, True): ("GFX10_SW_4K_S3_RBPLUS_PATINFO", 12),
    (9, True): ("GFX10_SW_64K_S3_RBPLUS_PATINFO", 16),
    (17, True): ("GFX10_SW_64K_S3_T_RBPLUS_PATINFO", 16),
    (21, True): ("GFX10_SW_4K_S3_X_RBPLUS_PATINFO", 12),
    (25, True): ("GFX10_SW_64K_S3_X_RBPLUS_PATINFO", 16),
    (26, True): ("GFX10_SW_64K_D3_X_RBPLUS_PATINFO", 16),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("header")
    ap.add_argument("out", nargs="?", default="runtime/gpu/gfx10_swizzle.inc")
    ap.add_argument("--pipes", default="32 pipes (8 PKRs)")
    a = ap.parse_args()
    nibbles, tables = load(a.header)
    rows = []
    for (mode, thick), (table, blk) in MODES.items():
        entries = tables.get(table)
        if not entries:
            sys.exit(f"{table} not in the header")
        for e in range(5):
            want = f"{a.pipes} {1 << e} bpe"
            entry = next((t for t in entries if t[5].startswith(want)), None)
            if entry is None:
                sys.exit(f"{table}: no entry for {want!r}")
            _, n01, n2, n3, n4, _ = entry
            bits = (list(nibbles["NIBBLE01"][n01]) + list(nibbles["NIBBLE2"][n2]) + list(nibbles["NIBBLE3"][n3]) +
                    list(nibbles["NIBBLE4"][n4]))[:blk]
            x = [v & 0xFFFF for v in bits]
            y = [(v >> 16) & 0xFFFF for v in bits]
            z = [(v >> 32) & 0xFFFF for v in bits]
            if any(v >> 48 for v in bits):
                sys.exit(f"{table} {e}: sample bits in a 1xaa pattern")
            pad = lambda m: ", ".join(f"0x{v:04x}" for v in m + [0] * (16 - len(m)))  # noqa: E731
            rows.append(f"{{{mode}, {str(thick).lower()}, {e}, {blk}, {{{pad(x)}}}, {{{pad(y)}}}, {{{pad(z)}}}}},")
    with open(a.out, "w", newline="\n") as f:
        f.write(f"// Generated by tools/gen_swizzle.py from addrlib's gfx10SwizzlePattern.h (MIT), {a.pipes}.\n")
        f.write("// {mode, thick, element log2, block log2, x masks, y masks, z masks} per address bit\n")
        f.write("\n".join(rows) + "\n")
    print(f"{len(rows)} equations -> {a.out}")


if __name__ == "__main__":
    main()
